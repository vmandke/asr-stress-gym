// Command matrix queries the running worker fleet and writes the M6
// compatibility matrix.  It deliberately learns identity and capabilities
// from /health rather than duplicating model knowledge in the gateway or in
// this command: an adapter change therefore cannot make the artifact drift.
package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
	"time"

	"asr-stress-gym/internal/backend"
)

const defaultWorkers = "worker-a=http://localhost:18001,worker-b=http://localhost:18002,worker-c=http://localhost:18003,worker-d=http://localhost:18004,worker-e=http://localhost:18005,worker-f=http://localhost:18007,worker-g=http://localhost:18008"

type worker struct {
	id     string
	url    string
	advert backend.WorkerAdvert
}

func main() {
	workersSpec := flag.String("workers", envOr("MATRIX_WORKER_URLS", defaultWorkers), "comma-separated id=url worker endpoints")
	out := flag.String("out", "docs/compat-matrix.md", "path for generated Markdown")
	timeout := flag.Duration("timeout", 5*time.Second, "per-worker health request timeout")
	flag.Parse()

	if err := run(context.Background(), *workersSpec, *out, *timeout); err != nil {
		fmt.Fprintln(os.Stderr, "matrix:", err)
		os.Exit(1)
	}
	fmt.Println("generated", *out)
}

func envOr(key, fallback string) string {
	if value := os.Getenv(key); value != "" {
		return value
	}
	return fallback
}

func run(ctx context.Context, spec, outputPath string, timeout time.Duration) error {
	endpoints, err := parseWorkers(spec)
	if err != nil {
		return err
	}

	workers := make([]worker, 0, len(endpoints))
	for _, endpoint := range endpoints {
		requestCtx, cancel := context.WithTimeout(ctx, timeout)
		advert, healthErr := backend.NewHTTPClient(endpoint.url).Health(requestCtx)
		cancel()
		if healthErr != nil {
			return fmt.Errorf("health %s (%s): %w", endpoint.id, endpoint.url, healthErr)
		}
		if advert.WorkerID == "" {
			return fmt.Errorf("health %s (%s): response has no worker_id", endpoint.id, endpoint.url)
		}
		workers = append(workers, worker{id: endpoint.id, url: endpoint.url, advert: advert})
	}

	return os.WriteFile(outputPath, []byte(render(workers)), 0o644)
}

type endpoint struct {
	id  string
	url string
}

func parseWorkers(spec string) ([]endpoint, error) {
	seen := make(map[string]bool)
	var endpoints []endpoint
	for _, part := range strings.Split(spec, ",") {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		id, url, ok := strings.Cut(part, "=")
		id, url = strings.TrimSpace(id), strings.TrimRight(strings.TrimSpace(url), "/")
		if !ok || id == "" || url == "" {
			return nil, fmt.Errorf("invalid worker entry %q (want id=url)", part)
		}
		if seen[id] {
			return nil, fmt.Errorf("duplicate worker id %q", id)
		}
		seen[id] = true
		endpoints = append(endpoints, endpoint{id: id, url: url})
	}
	if len(endpoints) < 2 {
		return nil, errors.New("need at least two workers to build a compatibility matrix")
	}
	return endpoints, nil
}

func render(workers []worker) string {
	// The endpoint order is intentional: it makes diffs stable while retaining
	// the caller's fleet order (mock, a, b, ... in the Makefile default).
	var b strings.Builder
	b.WriteString("# Compatibility matrix\n\n")
	b.WriteString("Generated by `make matrix` from each running worker's `/health` advertisement. ")
	b.WriteString("A fresh-state replay starts at the last committed final; checkpoint restore is available only when both sides advertise the same key and `serializable=true`.\n\n")
	b.WriteString("| Source | Target | Source key | Target key | Online recovery policy | Offline recovery policy |\n")
	b.WriteString("|---|---|---|---|---|---|\n")
	for _, source := range workers {
		for _, target := range workers {
			if source.id == target.id {
				continue
			}
			fmt.Fprintf(&b, "| %s | %s | `%s` | `%s` | %s | %s |\n",
				source.id,
				target.id,
				shortKey(source.advert.CompatibilityKeyHash),
				shortKey(target.advert.CompatibilityKeyHash),
				recoveryPolicy(source, target, "online"),
				recoveryPolicy(source, target, "offline"),
			)
		}
	}

	b.WriteString("\n## Fleet advertisements\n\n")
	b.WriteString("| Worker | Adapter model | Key | Streaming | Serializable | Modes | RTF p50 |\n")
	b.WriteString("|---|---|---|---|---|---|---|\n")
	for _, w := range workers {
		rtf := "not reported"
		if w.advert.RTFP50 != nil {
			rtf = fmt.Sprintf("%.3f", *w.advert.RTFP50)
		}
		fmt.Fprintf(&b, "| %s | %s | `%s` | %s | %s | %s | %s |\n",
			w.id,
			w.advert.Model,
			shortKey(w.advert.CompatibilityKeyHash),
			yesNo(w.advert.Capabilities.Streaming),
			yesNo(w.advert.Capabilities.Serializable),
			strings.Join(sortedStrings(w.advert.Capabilities.Modes), ", "),
			rtf,
		)
	}
	return b.String()
}

func recoveryPolicy(source, target worker, mode string) string {
	if !supportsMode(source.advert.Capabilities, mode) {
		return fmt.Sprintf("not applicable: source cannot serve %s traffic", mode)
	}
	if !supportsMode(target.advert.Capabilities, mode) {
		return fmt.Sprintf("refused by router: target cannot serve %s traffic", mode)
	}
	if mode == "online" && (!source.advert.Capabilities.Streaming || !target.advert.Capabilities.Streaming) {
		return "refused by router: target cannot serve online traffic"
	}
	if source.advert.CompatibilityKeyHash == target.advert.CompatibilityKeyHash &&
		source.advert.Capabilities.Serializable && target.advert.Capabilities.Serializable {
		return "checkpoint restore + tail replay"
	}
	return "fresh state + replay from last committed final"
}

func acceptsOnline(c backend.Capabilities) bool {
	return c.Streaming && supportsMode(c, "online")
}

func supportsMode(c backend.Capabilities, want string) bool {
	for _, mode := range c.Modes {
		if mode == want {
			return true
		}
	}
	return false
}

func sortedStrings(in []string) []string {
	out := append([]string(nil), in...)
	sort.Strings(out)
	return out
}

func shortKey(key string) string {
	if len(key) <= 16 {
		return key
	}
	return key[:16] + "…"
}

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}
